const languageKey = 'qms:locale:v1';
const translate = (locale: Locale, text: string) => locale === 'en-US' ? translations[text] ?? text : text;
const LanguageContext = createContext({ locale: 'zh-CN' as Locale, setLocale: (_locale: Locale) => {}, t: (text: string) => text });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    try { return localStorage.getItem(languageKey) === 'en-US' ? 'en-US' : 'zh-CN'; } catch { return 'zh-CN'; }
  });
  useEffect(() => {
    document.documentElement.lang = locale;
    try { localStorage.setItem(languageKey, locale); } catch {}
  }, [locale]);
  const value = useMemo(() => ({ locale, setLocale, t: (text: string) => translate(locale, text) }), [locale]);
  return <LanguageContext.Provider value={value}><ConfigProvider locale={locale === 'en-US' ? english : chinese}>{children}</ConfigProvider></LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);

export function LanguageSwitcher() {
  const { locale, setLocale } = useLanguage();
  const [open, setOpen] = useState(false);
  const triggerRef = useRef<HTMLButtonElement>(null);
  function handleOpenChange(nextOpen: boolean) {
    setOpen(nextOpen);
    if (!nextOpen) queueMicrotask(() => triggerRef.current?.focus());
  }
  return <Dropdown open={open} onOpenChange={handleOpenChange} trigger={['click']} placement="bottomRight" autoFocus menu={{
    selectable: true,
    selectedKeys: [locale],
    items: ([{ key: 'zh-CN', label: '简体中文' }, { key: 'en-US', label: 'English' }] as const).map(item => ({
      ...item,
      role: 'menuitemradio',
      'aria-checked': item.key === locale,
      icon: <Check size={14} aria-hidden="true" style={{ visibility: item.key === locale ? 'visible' : 'hidden' }} />,
    })),
    onClick: ({ key, domEvent }) => { domEvent.preventDefault(); setLocale(key as Locale); handleOpenChange(false); },
  }}>
    <Button ref={triggerRef} className="language-switcher" aria-label="Language / 语言" aria-haspopup="menu" aria-expanded={open} icon={<Languages size={17} aria-hidden="true" />}>
      <span>{locale === 'zh-CN' ? '中文' : 'EN'}</span><ChevronDown size={13} aria-hidden="true" />
    </Button>
  </Dropdown>;
}
