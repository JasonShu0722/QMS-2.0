import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { ConfigProvider } from 'antd';
import { MemoryRouter } from 'react-router-dom';
import { beforeEach, afterEach, expect, it, vi } from 'vitest';
import { ApiError, apiRequest, csrfToken } from '../../api/client';
import { LanguageProvider } from '../../i18n/Language';
import { UnsavedChangesProvider } from '../../layouts/UnsavedChanges';
import { useWorkTabsStore } from '../../work-tabs/workTabsStore';
import { readXlsxFile } from '../imports/read-xlsx';
import { ComponentProjectImport, parseComponentProjectRows } from './ComponentProjectImport';

vi.mock('../imports/read-xlsx', () => ({ readXlsxFile: vi.fn() }));
vi.mock('../../api/client', async () => ({ ...await vi.importActual('../../api/client'), apiRequest: vi.fn(), csrfToken: vi.fn() }));
beforeEach(() => {
  localStorage.clear(); useWorkTabsStore.getState().bindSession('INTERNAL:org-a:user-a');
  vi.mocked(csrfToken).mockResolvedValue('csrf'); vi.mocked(apiRequest).mockReset();
  vi.mocked(apiRequest).mockResolvedValue({ created: 1, skipped: 0, failed: 0, items: [{ rowNumber: 2, code: '0001.2-A', status: 'CREATED' }] });
  vi.mocked(readXlsxFile).mockResolvedValue([['组件号', '组件名称'], ['0001.2-A', '总成,（甲）^^']]);
});
afterEach(() => { useWorkTabsStore.getState().reset(); });

it.each([
  [['组件号', '组件名称']],
  [['PROD_ID', 'MTRL_NAME']],
  [['成品编码', '物料名称']],
  [[' PROD_ID\r\n成品编码 ', ' MTRL_NAME\n物料名称 ']],
].map(headers => ({ headers })))('accepts exact component header aliases $headers without rewriting codes or names', ({ headers }) => {
  expect(parseComponentProjectRows([...headers, [' 0001.2-A ', ' 总成,（甲）^^ ']])).toEqual([{ rowNumber: 2, componentCode: '0001.2-A', componentName: '总成,（甲）^^' }]);
});

it.each([
  [['PROD_ID', 'MTRL_NAME'], ['成品编码', '物料名称']],
  [['物料名称', '成品编码'], ['MTRL_NAME', 'PROD_ID']],
].map(headers => ({ headers })))('skips only an immediate corresponding bilingual second header $headers and retains row numbers', ({ headers }) => {
  const reversed = headers[0][0] === '物料名称';
  expect(parseComponentProjectRows([...headers, [], reversed ? ['名称', '0007'] : ['0007', '名称']])).toEqual([{ rowNumber: 4, componentCode: '0007', componentName: '名称' }]);
});

it('does not drop normal data that happens to match aliases under a standard header', () => {
  expect(parseComponentProjectRows([['组件号', '组件名称'], ['PROD_ID', 'MTRL_NAME'], ['成品编码', '物料名称']])).toEqual([
    { rowNumber: 2, componentCode: 'PROD_ID', componentName: 'MTRL_NAME' },
    { rowNumber: 3, componentCode: '成品编码', componentName: '物料名称' },
  ]);
});

it('marks non-text codes invalid for server row validation without converting them to text or numbers', () => {
  expect(parseComponentProjectRows([['组件号', '组件名称'], [123, '名称']])).toEqual([{ rowNumber: 2, componentCode: '', componentName: '名称' }]);
});

it.each([
  [['物料编码', '物料名称'], ['1', 'x']],
  [['PROD_ID', '未知字段'], ['1', 'x']],
  [['组件号', '组件号'], ['1', 'x']],
  [['组件号', '组件名称', '项目'], ['1', 'x', 'P1']],
  [['组件号', '组件名称'], ['1', { formula: '1+1' }]],
  [['组件号', '组件名称'], ['1', { richText: [] }]],
  [['组件号', '组件名称'], ['1', 'x', 'unexpected']],
].map(sheet => ({ sheet })))('rejects unknown headers, objects, formulas and extra data columns $sheet', ({ sheet }) => {
  expect(() => parseComponentProjectRows(sheet)).toThrow();
});

it('preserves sparse original row numbers and reports the original bad row', () => {
  expect(parseComponentProjectRows([['组件号', '组件名称'], [], ['001', 'A']])[0].rowNumber).toBe(3);
  expect(() => parseComponentProjectRows([['组件号', '组件名称'], [], ['001', 'A', 'extra']])).toThrow('3');
  expect(() => parseComponentProjectRows([['组件号', '组件名称'], []])).toThrow();
});

it('reads the exact translated standard template generated by the house importer', () => {
  const labels: Record<string, string> = { '组件号': 'Component code', '组件名称': 'Component name' };
  const translate = (text: string) => labels[text] ?? text;
  expect(parseComponentProjectRows([['Component code', 'Component name'], ['0007', 'Name, (A)^^']], translate)).toEqual([{ rowNumber: 2, componentCode: '0007', componentName: 'Name, (A)^^' }]);
});

function mount(organizationId = 'org-a', onImported = vi.fn(), onUnauthorized = vi.fn()) {
  const view = render(<ConfigProvider theme={{ token: { motion: false } }}><LanguageProvider><MemoryRouter><UnsavedChangesProvider><ComponentProjectImport organizationId={organizationId} onImported={onImported} onUnauthorized={onUnauthorized} /></UnsavedChangesProvider></MemoryRouter></LanguageProvider></ConfigProvider>);
  return { ...view, onImported, onUnauthorized };
}
async function upload() {
  fireEvent.click(screen.getByRole('button', { name: '批量导入组件' }));
  fireEvent.change(screen.getByLabelText('组件清单文件'), { target: { files: [new File(['xlsx'], 'components.xlsx')] } });
  await screen.findByText('0001.2-A');
}

it('reuses the real importer with component fields, body scope, CSRF and idempotency', async () => {
  const { onImported } = mount(); await upload();
  expect(readXlsxFile).toHaveBeenCalledWith(expect.any(File), { mode: 'master-data' });
  fireEvent.click(screen.getByRole('button', { name: '导入组件' }));
  await waitFor(() => expect(onImported).toHaveBeenCalledTimes(1));
  expect(apiRequest).toHaveBeenCalledWith('/api/v1/admin/configuration/component-project-mappings/import', expect.objectContaining({
    method: 'POST', headers: { 'x-csrf-token': 'csrf', 'Idempotency-Key': expect.any(String) },
    body: JSON.stringify({ organizationId: 'org-a', rows: [{ rowNumber: 2, componentCode: '0001.2-A', componentName: '总成,（甲）^^' }] }),
  }));
  expect(vi.mocked(apiRequest).mock.calls.every(([path]) => !path.includes('material-masters'))).toBe(true);
});

it('retries an unknown import using the same frozen batch body and key', async () => {
  vi.mocked(apiRequest).mockRejectedValueOnce(new TypeError('network'));
  mount(); await upload(); fireEvent.click(screen.getByRole('button', { name: '导入组件' }));
  await screen.findByText('当前批次结果未知，请使用原批次重试；已确认结果保留。');
  fireEvent.click(screen.getByRole('button', { name: '导入组件' }));
  await waitFor(() => expect(apiRequest).toHaveBeenCalledTimes(2));
  expect(vi.mocked(apiRequest).mock.calls[1]).toEqual(vi.mocked(apiRequest).mock.calls[0]);
});

it('drops a late parsing result on session replacement', async () => {
  let finish!: (value: unknown[][]) => void;
  vi.mocked(readXlsxFile).mockReturnValueOnce(new Promise(resolve => { finish = resolve; }));
  mount();
  fireEvent.click(screen.getByRole('button', { name: '批量导入组件' }));
  fireEvent.change(screen.getByLabelText('组件清单文件'), { target: { files: [new File(['xlsx'], 'components.xlsx')] } });
  act(() => useWorkTabsStore.getState().bindSession('INTERNAL:org-a:user-b'));
  await act(async () => finish([['组件号', '组件名称'], ['0001', '旧会话组件']]));
  expect(screen.queryByText('旧会话组件')).not.toBeInTheDocument();
  expect(apiRequest).not.toHaveBeenCalled();
});

it('forwards a current import 401 to its host, stops remaining batches and does not refresh acknowledged old-scope results', async () => {
  const expired = new ApiError({ code: 'AUTH_SESSION_REQUIRED', message: 'expired' }, 401);
  vi.mocked(readXlsxFile).mockResolvedValue([['组件号', '组件名称'], ['0001.2-A', '总成'], ...Array.from({ length: 200 }, (_, index) => [`C-${index}`, `组件${index}`])]);
  vi.mocked(apiRequest).mockResolvedValueOnce({ created: 100, skipped: 0, failed: 0, items: [] }).mockRejectedValueOnce(expired);
  const { onImported, onUnauthorized } = mount(); await upload();
  fireEvent.click(screen.getByRole('button', { name: '导入组件' }));
  await waitFor(() => expect(onUnauthorized).toHaveBeenCalledWith(expired));
  expect(apiRequest).toHaveBeenCalledTimes(2);
  expect(onImported).not.toHaveBeenCalled();
});

it('does not forward a late old-session import 401 into the replacement session', async () => {
  let reject!: (error: unknown) => void;
  vi.mocked(apiRequest).mockReturnValueOnce(new Promise((_resolve, fail) => { reject = fail; }));
  const { onImported, onUnauthorized } = mount(); await upload();
  fireEvent.click(screen.getByRole('button', { name: '导入组件' }));
  await waitFor(() => expect(apiRequest).toHaveBeenCalledTimes(1));
  act(() => useWorkTabsStore.getState().bindSession('INTERNAL:org-a:user-b'));
  await act(async () => reject(new ApiError({ code: 'AUTH_SESSION_REQUIRED', message: 'expired' }, 401)));
  expect(onUnauthorized).not.toHaveBeenCalled();
  expect(onImported).not.toHaveBeenCalled();
  expect(useWorkTabsStore.getState().sessionScope).toBe('INTERNAL:org-a:user-b');
});
