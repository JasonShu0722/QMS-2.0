import { PLATFORM_ERROR_CODES, PLATFORM_ERROR_MESSAGES } from '../../src/common/contracts/platform-error.js';

it.each(['PROCESS_EIGHT_D_CONFIGURATION_REQUIRED', 'PROCESS_EIGHT_D_APPROVAL_LOCKED', 'PROCESS_EIGHT_D_ANALYSIS_INCOMPLETE',
  'PROCESS_EIGHT_D_SUBMISSION_INCOMPLETE', 'PROCESS_EIGHT_D_SOURCE_CONFIRMATION_REQUIRED', 'PROCESS_EIGHT_D_REPORT_VERSION_CONFLICT',
  'PROCESS_PRODUCTION_QUANTITY_INCOMPLETE', 'PROCESS_DEFECT_MATERIAL_NOT_FOUND', 'PROCESS_DEFECT_STATUS_CONFLICT'])('preserves the safe process error %s at the HTTP boundary', code => {
  expect(PLATFORM_ERROR_CODES).toContain(code);
  expect(PLATFORM_ERROR_MESSAGES[code as keyof typeof PLATFORM_ERROR_MESSAGES]).toMatch(/[\u4e00-\u9fff]/);
});
